from pprint import pprint
import sys

class Range:
    def __init__(self, start, end, value):
        self.start = start
        self.end = end
        self.value = value

    def __repr__(self):
        return f'Range({self.start:x}, {self.end:x}, {self.value})'

def make_ranges():
    ranges = []
    last = 0
    next = 0x110000
    for line in open("UnicodeData.txt", "r"):
        code_point = int(line.split(";")[0], 16)
        if next != 0x110000 and next != code_point:
            # Missing chars are Cn, not printable
            value = False
            if ranges and ranges[-1].value == value:
                # Extend current range
                ranges[-1].end = code_point - 1
            else:
                # Add a new range
                ranges.append(Range(last + 1, code_point - 1, value))
        # "Cc" is "control", "Cf" is "format"
        value = line.split(";")[2][0] != 'C'
        if 0:
            print(f'{code_point=:x} {value=}')
        if ranges and ranges[-1].value == value:
            # Extend current range
            ranges[-1].end = code_point
        else:
            # Start a new range
            ranges.append(Range(code_point, code_point, value))
        if line.split(";")[1].endswith(" First>"):
            # Next entry will be " Last>" and value applies for
            # everything in that range.  Set next to 0x110000.
            next = 0x110000
        else:
            next = code_point + 1
            last = code_point
    if ranges[-1].end < 0x10FFFE:
        if ranges[-1].value:
            ranges.append(Range(ranges[-1].end + 1, 0x10FFFE, False))
        else:
            ranges[-1].end = 0x10FFFE
    return ranges

if len(sys.argv) != 2:
    print("usage: %s <unicode version>" % sys.argv[0], file=sys.stderr)
    sys.exit(1)
unicode_version = sys.argv[1]

ranges = make_ranges()
if 0:
    pprint(ranges)

print(f"/* Generated by contrib/unicode/gen-printable-chars.py")
print(f"   using version {unicode_version}"
      " of the Unicode standard.  */")
print("\nstatic const cppchar_t printable_range_ends[] = {", end="")
for i, r in enumerate(ranges):
    if i % 8:
        print(" ", end="")
    else:
        print("\n  ", end="")
    print("0x%x," % r.end, end="")
print("\n};\n")
print("static const bool is_printable[] = {", end="")
for i, r in enumerate(ranges):
    if i % 24:
        print(" ", end="")
    else:
        print("\n  ", end="")
    if r.value:
        print("1,", end="")
    else:
        print("0,", end="")
print("\n};")
